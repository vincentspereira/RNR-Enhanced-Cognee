def sha(data):
    return hashlib.sha256(data).hexdigest()

def save(name, data):
    with (OUT / name).open('x', encoding='ascii') as f:
        json.dump(data, f, indent=2, sort_keys=True, ensure_ascii=True)
        f.write('\n')

