scan = {}
for path in PINS:
    text = (ROOT / path).read_text()
    tree = ast.parse(text)
    bad = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            fn = ast.unparse(node.func)
            if fn in {'eval', 'exec', 'os.system', 'pickle.load', 'pickle.loads'}:
                bad.append({'line': node.lineno, 'call': fn})
            if any(k.arg == 'shell' and isinstance(k.value, ast.Constant) and k.value.value is True for k in node.keywords):
                bad.append({'line': node.lineno, 'call': fn, 'shell_true': True})
            if fn.endswith('.execute') and node.args and isinstance(node.args[0], ast.JoinedStr):
                bad.append({'line': node.lineno, 'call': fn, 'formatted_sql_candidate': True})
    secret_lines = [i for i, line in enumerate(text.splitlines(), 1)
                    if re.search(r'(?i)(api_key|secret|password|token|passwd)\s*=\s*[\x22\x27][^\x22\x27]{6,}[\x22\x27]', line)]
    scan[path] = {'dangerous_call_hits': bad, 'secret_assignment_regex_lines': secret_lines,
                  'manual_review': 'No real secret assignments found. Secret-bearing test strings are explicitly invented refusal canaries. Fixed helper importlib exec_module is not dynamic eval/exec input.',
                  'subprocess_review': 'Helper has only selected systemctl show via shell=False and fixed sanitized env. Tests launch the fixed helper as ordinary user in a sandbox.'}
save('static-security-assessment.json', scan)

